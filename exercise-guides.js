(function(){
  'use strict';
  function escGuide(s){return String(s??'').replace(/[&<>"']/g,m=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[m]));}
  window.exerciseGuideMarkup=function(name){
    const g=window.EXERCISE_GUIDES?.[name];
    if(!g)return '';
    if(!g.image)return '<button type="button" class="exercise-guide-empty" onclick="openExerciseGuide(\''+escGuide(name).replace(/'/g,"\\'")+'\')" aria-label="Abrir guia de '+escGuide(name)+'">📘</button>';
    return '<button type="button" class="exercise-guide-thumb" onclick="openExerciseGuide(\''+escGuide(name).replace(/'/g,"\\'")+'\')" aria-label="Abrir guia de '+escGuide(name)+'"><img src="'+g.image+'" alt="Guia de execução: '+escGuide(name)+'" loading="lazy"></button>';
  };
  window.openExerciseGuide=function(name){
    const g=window.EXERCISE_GUIDES?.[name]; if(!g)return;
    let modal=document.getElementById('exercise-guide-modal');
    if(!modal){
      modal=document.createElement('div');modal.id='exercise-guide-modal';modal.className='exercise-guide-modal';modal.setAttribute('role','dialog');modal.setAttribute('aria-modal','true');
      modal.innerHTML='<div class="exercise-guide-backdrop" onclick="closeExerciseGuide()"></div><div class="exercise-guide-dialog"><button type="button" class="exercise-guide-close" onclick="closeExerciseGuide()" aria-label="Fechar">×</button><div id="exercise-guide-content"></div></div>';
      document.body.appendChild(modal);
    }
    const image=g.image?'<img class="exercise-guide-large" src="'+g.image+'" alt="Guia de execução: '+escGuide(name)+'">':'<div class="exercise-guide-noimage">Não há uma ilustração correspondente a este exercício na pasta enviada.</div>';
    const tips=(g.tips||[]).map(t=>'<li>'+escGuide(t)+'</li>').join('');
    document.getElementById('exercise-guide-content').innerHTML='<div class="exercise-guide-title">📘 '+escGuide(name)+'</div>'+image+'<div class="exercise-guide-tips"><b>DICAS DE EXECUÇÃO</b><ul>'+tips+'</ul></div>';
    modal.classList.add('open');document.body.classList.add('guide-modal-open');
  };
  window.closeExerciseGuide=function(){
    const modal=document.getElementById('exercise-guide-modal');if(modal)modal.classList.remove('open');document.body.classList.remove('guide-modal-open');
  };
  document.addEventListener('keydown',e=>{if(e.key==='Escape')window.closeExerciseGuide();});
})();
